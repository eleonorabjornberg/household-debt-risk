#!/usr/bin/env python3
"""Write the Claude-draft E1 results note (RESULTS.md) and its register rows (claims/tracks/infra.csv).

    uv run --project pipeline python evals/e1_sql_benchmark/write_results.py

Every number in the note comes from run-2026-11-05b/analysis.json (analyze_e1.py, the pre-registered tests) or
run-2026-11-05b/summary.json and the run directories' call logs (spend). Each published number gets a register row
pointing at the note's line that shows it; validation UNVERIFIED (traced to a results file, no independent check).
Re-run after any change to the results; never edit the numbers by hand. The baseline section stays open until
Eleonora's e1-baseline answer.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
RUN = HERE / "run-2026-11-05b"
NOTE = HERE / "RESULTS.md"
TRACK = ROOT / "claims" / "tracks" / "infra.csv"
SCHEMA = ["claim_id", "claim", "display", "value", "unit", "period", "locations", "computation", "series_ids",
          "vintage", "validation", "check_id", "notes"]
NAMES = {"claude-opus-5-5": "Opus 5.5", "claude-sonnet-5-5": "Sonnet 5.5", "claude-haiku-5-5": "Haiku 5.5"}
SHORT = {"claude-opus-5-5": "opus", "claude-sonnet-5-5": "sonnet", "claude-haiku-5-5": "haiku"}
ORDER = ["claude-opus-5-5", "claude-sonnet-5-5", "claude-haiku-5-5"]


def spend(d: Path) -> float:
    f = d / "calls.jsonl"
    return sum(json.loads(l).get("cost_usd", 0) for l in f.read_text().splitlines() if l.strip()) if f.exists() else 0.0


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def main() -> None:
    a = json.loads((RUN / "analysis.json").read_text())
    s = json.loads((RUN / "summary.json").read_text())
    vint = json.loads((ROOT / "web/public/data/meta.json").read_text())["vintages"]
    lines: list[str] = []
    rows: list[dict] = []

    def claim(cid, text, display, value, unit, computation, notes=""):
        """Register `display` as shown on the NEXT line appended to the note."""
        rows.append({"claim_id": f"e1_{cid}", "claim": text, "display": display, "value": value, "unit": unit,
                     "period": "E1 run 2026-11-05", "locations": f"evals/e1_sql_benchmark/RESULTS.md:{len(lines) + 1}",
                     "computation": computation, "series_ids": "",
                     "vintage": f"z1:{vint['z1']} nyfed:{vint['nyfed']}", "validation": "UNVERIFIED", "check_id": "",
                     "notes": ("E1 benchmark result (Claude draft note). " + notes).strip()})

    ana = "evals/e1_sql_benchmark/analyze_e1.py -> run-2026-11-05b/analysis.json (bootstrap, seed 20261104)"
    summ = "run-2026-11-05b/summary.json and calls.jsonl (logged usage x live prices, 2026-11-05)"
    lines += [
        "> **Claude draft.** Written by Claude from the E1 results files; Eleonora's text replaces it. The design is hers "
        "(docs/decisions/e1-prereg.md, frozen `e0ae2d6`, with dated deviations D1–D5). Every number here has a row in "
        "the claims register (`e1_*`), generated by `write_results.py`.",
        "",
        "# E1 question-to-SQL benchmark: results (draft)",
        "",
        "Run `run-2026-11-05b`: 80 scored questions (60 answerable, 20 unanswerable) × Haiku, Sonnet and Opus 5.5 × 3 "
        "repetitions = 720 tool-use loops through the household-credit MCP tools (snapshot backend, Z.1 vintage "
        f"{vint['z1']}). It completed with no stop and 0 API errors. The 20 held-out questions were not run.",
        "",
        "**Read with the deviations.** The first 79 loops ran before D4 (the recalibrated stops), under D2 and D3; the "
        "run was resumed from loop 80 under D4 and D5. The scorer fix D1 applied to every loop. The pilot (10 easy "
        "questions) was seen before the design was fixed. Claude wrote the questions (CHOICE-E1-3 (a)), so their style "
        "may favour Claude models.",
        "",
        "## Pre-registered tests (unit (ii): every repetition, clustered by question; T = R = 70%; Holm per family)",
        "",
        "| Test | Model | Rate | 95% interval (question bootstrap) | Holm p | Verdict |",
        "|---|---|---|---|---|---|",
    ]
    for fam, label, thr in (("H1", "H1 accuracy ≥ 70% (60 answerable)", "T"), ("H3", "H3 refusals ≥ 70% (20 unanswerable)", "R")):
        for m in ORDER:
            v = a[fam][m]
            lo, hi = v["ci95"]
            p = "< 0.0001" if v["p_holm"] == 0 else f"{v['p_holm']:.3f}"
            disp = pct(v["rate"])
            claim(f"{fam.lower()}_{SHORT[m]}_rate", f"E1 {fam}: {NAMES[m]} rate {disp} ({v['n_answers']} answers, "
                  f"{v['n_questions']} questions), pre-registered test, verdict {v['verdict']}.", disp,
                  f"{v['rate']:.4f}", "share", ana)
            lines.append(f"| {label} | {NAMES[m]} | {disp} | {pct(lo)} to {pct(hi)} | {p} | {v['verdict']} |")
            # register the interval bounds on the same line
            for tag, b in (("lo", lo), ("hi", hi)):
                rows.append({**rows[-1], "claim_id": f"e1_{fam.lower()}_{SHORT[m]}_ci_{tag}",
                             "claim": f"E1 {fam}: {NAMES[m]} 95% bootstrap interval {'lower' if tag == 'lo' else 'upper'} "
                                      f"bound {pct(b)}.", "display": pct(b), "value": f"{b:.4f}"})
    lines += ["", "| H2 (paired, clustered) | Difference in accuracy | Discordant answers | Holm p | Verdict |",
              "|---|---|---|---|---|"]
    for k, v in a["H2"].items():
        x, y = k.split(" vs ")
        d = f"{100 * v['diff_a_minus_b']:+.1f} pp"
        tag = f"{SHORT[x]}_{SHORT[y]}"
        claim(f"h2_{tag}_diff", f"E1 H2: {NAMES[x]} minus {NAMES[y]} accuracy {d} on the answerable questions; "
              f"Holm-adjusted p {v['p_holm']:.3f}; {v['verdict']}.", d, f"{100 * v['diff_a_minus_b']:.2f}", "pp", ana)
        lines.append(f"| {NAMES[x]} vs {NAMES[y]} | {d} | {v['discordant_a_only']} vs {v['discordant_b_only']} | "
                     f"{v['p_holm']:.3f} | {v['verdict']} |")
        rows.append({**rows[-1], "claim_id": f"e1_h2_{tag}_p", "claim": f"E1 H2: {NAMES[x]} vs {NAMES[y]} Holm-adjusted "
                     f"p {v['p_holm']:.3f}.", "display": f"{v['p_holm']:.3f}", "value": f"{v['p_holm']:.3f}", "unit": "p"})

    lines += ["", "## Cost (measured: logged usage × live prices, checked 2026-11-05)", "",
              "| Model | Spent | Mean per loop | Correct (of 240) | Cost per correct answer |", "|---|---|---|---|---|"]
    for m in ORDER:
        v = s["per_model"][m]
        cpc = v["spent_usd"] / v["correct"]
        disp = f"${v['spent_usd']:.2f}"
        claim(f"cost_{SHORT[m]}", f"E1 main run: {NAMES[m]} spent {disp} over 240 loops.", disp,
              f"{v['spent_usd']:.6f}", "usd", summ)
        lines.append(f"| {NAMES[m]} | {disp} | ${v['mean_per_loop_usd']:.4f} | {v['correct']} | ${cpc:.4f} |")
        for cid, txt, dv, val in ((f"cost_per_loop_{SHORT[m]}", "mean cost per loop", f"${v['mean_per_loop_usd']:.4f}",
                                   f"{v['mean_per_loop_usd']:.6f}"),
                                  (f"cost_per_correct_{SHORT[m]}", "cost per correct answer", f"${cpc:.4f}", f"{cpc:.6f}")):
            rows.append({**rows[-1], "claim_id": f"e1_{cid}", "claim": f"E1 main run: {NAMES[m]} {txt} {dv}.",
                         "display": dv, "value": val})
    main_spend = spend(RUN)
    total = sum(spend(d) for d in HERE.glob("run-*") if "fake" not in d.name)
    lines.append("")
    claim("spend_main", "E1 main run run-2026-11-05b spend (all 720 loops, incl. the interrupted 80th loop).",
          f"${main_spend:.2f}", f"{main_spend:.6f}", "usd", summ)
    lines.append(f"Main run spend: ${main_spend:.2f}. All E1 spend so far, every run directory against the one $31 cap "
                 "(the stopped `run-2026-11-05`, this run, and the baseline so far):")
    claim("spend_total", "All E1 API spend so far across run directories, against the $31 cap.", f"${total:.2f}",
          f"{total:.6f}", "usd", "sum of cost_usd over evals/e1_sql_benchmark/run-*/calls.jsonl (not fake runs)",
          "Recounted independently by the coordinator from the call logs ($18.131656 at 22:50 UTC).")
    lines.append(f"${total:.2f} of $31.")
    lines += ["", "## What the misses were (checked by Claude, answer by answer; no scorer artifacts)", "",
              "- Opus declined three questions that compare NY Fed and Z.1 figures (q128, q173, q175) six times, arguing "
              "the two sources are not comparable. The frozen rule scores these as wrong.",
              "- Several loops hit the 4-turn limit while still fetching data (q122 for all three models; q184 for Opus and "
              "Sonnet).",
              "- Four answers of 36.2 on q156 (gold 36.216, tolerance $0.01 trillion) miss by rounding to one decimal, "
              "under the tolerance in the approved set.",
              "", "## Opus no-tools baseline (descriptive; no pre-registered test)", ""]
    base = HERE / "run-2026-11-05-baseline"
    bs = json.loads((base / "summary.json").read_text())
    br = [json.loads(l) for l in (base / "results.jsonl").read_text().splitlines() if l.strip()]
    if bs["loops_done"] < bs["loops_planned"] or bs.get("stop"):
        lines.append(f"**Partial:** {bs['loops_done']} of {bs['loops_planned']} loops ({bs['stop'] and bs['stop']['reason']}).")
        lines.append("")
    mr = [json.loads(l) for l in (RUN / "results.jsonl").read_text().splitlines() if l.strip()]
    lines += ["`run-2026-11-05-baseline`: Opus 5.5 with no tools, answering from memory, on the same 80 questions × 3 "
              "repetitions. It stopped after 24 loops at a false checkpoint (deviation D6) and was resumed from loop 25. "
              "It is compared with Opus 5.5 with tools from the main run.", "",
              "| Opus 5.5 | Answerable correct | Refusals correct | Spent | Mean per loop |", "|---|---|---|---|---|"]
    def rate(rs, un):
        x = [r for r in rs if (r["family"] == "UN") == un]
        return sum(r["correct"] for r in x) / len(x), len(x)
    opus_main = [r for r in mr if r["model"] == "claude-opus-5-5"]
    for tag, label, rs, sp, mean in (
            ("tools", "with tools (main run)", opus_main, s["per_model"]["claude-opus-5-5"]["spent_usd"],
             s["per_model"]["claude-opus-5-5"]["mean_per_loop_usd"]),
            ("notools", "no tools (baseline)", br, spend(base), spend(base) / max(1, len(br)))):
        (ra, na), (rr, nr) = rate(rs, False), rate(rs, True)
        da, dr, ds = pct(ra), pct(rr), f"${sp:.2f}"
        claim(f"baseline_{tag}_answerable", f"E1: Opus 5.5 {label} answered {da} of {na} answerable-question answers "
              "correctly (descriptive).", da, f"{ra:.4f}", "share", "run-2026-11-05-baseline/results.jsonl and "
              "run-2026-11-05b/results.jsonl, scored by pilot.score (D1)")
        lines.append(f"| {label} | {da} (of {na}) | {dr} (of {nr}) | {ds} | ${mean:.4f} |")
        rows.append({**rows[-1], "claim_id": f"e1_baseline_{tag}_refusals", "display": dr, "value": f"{rr:.4f}",
                     "claim": f"E1: Opus 5.5 {label} correct refusals {dr} of {nr} unanswerable-question answers (descriptive)."})
        if tag == "notools":
            rows.append({**rows[-1], "claim_id": "e1_baseline_spend", "display": ds, "value": f"{sp:.6f}", "unit": "usd",
                         "claim": f"E1: Opus 5.5 no-tools baseline spend {ds} (all loops, incl. before the D6 resume)."})
    ans_b = [r for r in br if r["family"] != "UN"]
    no_num = sum(r["parsed"] is None for r in ans_b)
    disp = f"{no_num} of {len(ans_b)}"
    lines.append("")
    claim("baseline_notools_no_number", f"E1: Opus 5.5 with no tools gave no number on {disp} answerable-question "
          "answers (it declined them).", disp, str(no_num), "count", "run-2026-11-05-baseline/results.jsonl (parsed is null)")
    lines.append(f"Without tools, Opus declined to give a number on {disp} answerable-question answers, so its high "
                 "refusal rate reflects declining nearly everything, not telling answerable from unanswerable questions.")
    lines += ["", "The baseline has no pre-registered test (CHOICE-E1-12 (b)); it shows what the tools add. "
              "A no-tools answer is scored by the same rule, against the same gold.", ""]
    NOTE.write_text("\n".join(lines))
    keep = []
    if TRACK.exists():
        keep = [r for r in csv.DictReader(TRACK.open()) if not r["claim_id"].startswith("e1_")]
    with TRACK.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=SCHEMA)
        w.writeheader()
        w.writerows(keep + rows)
    print(f"{NOTE.name}: {len(lines)} lines; {len(rows)} register rows -> {TRACK.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
